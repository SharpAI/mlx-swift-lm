#!/usr/bin/env python3
"""Regenerate Tests/MLXLMTests/Conformance/ConformanceExpectations.swift.

Reads scripts/conformance/model-coverage.csv (the static vLLM-vs-us survey) and the
type-registry sources, and writes one expectation per distinct `model_type`:
whether a creator for it is registered in the LLM / VLM / embedder registries.

The expectation is a *snapshot of the registries' current contents* (static grep of
`"type": ...` keys). ConformanceRegistryTests compares it with the real registries at
runtime, so a mismatch is either a registry change (regression, or upstream landed a
model) or a bug in this grep. Re-run after intentionally changing the registries.

usage: gen_expectations.py [repo-root]
"""
import csv, os, re, sys

root = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), "..", "..")
root = os.path.abspath(root)

REGISTRY_FILES = {
    "llm": "Libraries/MLXLLM/LLMModelFactory.swift",
    "vlm": "Libraries/MLXVLM/VLMModelFactory.swift",
    "embedder": "Libraries/MLXEmbedders/ModelFactory.swift",
}
TYPE_REGISTRY = {"llm": "LLMTypeRegistry", "vlm": "VLMTypeRegistry", "embedder": "EmbedderTypeRegistry"}


def registry_keys(path, enum_name):
    src = open(os.path.join(root, path), encoding="utf8").read()
    start = src.index(f"enum {enum_name}")
    m = re.search(r"\.init\(creators:\s*\[", src[start:])
    body_start = start + m.end()
    depth, i = 1, body_start
    while depth:
        c = src[i]
        depth += (c == "[") - (c == "]")
        i += 1
    body = src[body_start:i - 1]
    # top-level entries look like  "name": ...  at the start of a line (4-8 spaces of indent)
    return set(re.findall(r'^\s{8}"([A-Za-z0-9_.\-]+)"\s*:', body, re.M))


keys = {k: registry_keys(REGISTRY_FILES[k], TYPE_REGISTRY[k]) for k in REGISTRY_FILES}

rows = list(csv.DictReader(open(os.path.join(root, "scripts/conformance/model-coverage.csv"), encoding="utf8")))
by_type = {}
skipped = []
for r in rows:
    mt = (r["model_type"] or "").strip()
    if not mt or mt.lower() == "none" or " " in mt or "/" in mt:
        skipped.append(f"{r.get('repo') or r.get('arch')}: model_type={mt!r}")
        continue
    by_type.setdefault(mt, []).append(r)


def swift_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


lines = []
for mt in sorted(by_type):
    where = [k for k in ("llm", "vlm", "embedder") if mt in keys[k]]
    archs = sorted({r["arch"] for r in by_type[mt]})
    status = sorted({r["our_status"] for r in by_type[mt]})
    lines.append(
        f"        .init(modelType: {swift_str(mt)}, registries: [{', '.join('.' + w for w in where)}], "
        f"archs: [{', '.join(swift_str(a) for a in archs)}], "
        f"surveyStatus: {swift_str('/'.join(status))}),"
    )

key_lines = [f"        .{k}: [{', '.join(swift_str(x) for x in sorted(keys[k]))}]," for k in ("llm", "vlm", "embedder")]

out = f"""// GENERATED by scripts/conformance/gen_expectations.py -- do not edit by hand.
// Source: scripts/conformance/model-coverage.csv (static survey, vLLM dc45a5f vs SharpAI main).

enum ConformanceRegistry: String, CaseIterable, Hashable {{
    case llm, vlm, embedder
}}

struct ConformanceExpectation {{
    /// HF `model_type` as it appears in config.json.
    let modelType: String
    /// Registries that must (and may only) contain a creator for `modelType`.
    /// Empty means "known missing": the harness expects it to be absent.
    let registries: [ConformanceRegistry]
    /// vLLM architecture names that map to this model_type (for reports).
    let archs: [String]
    /// The survey's static judgement, informational only -- never asserted.
    let surveyStatus: String
}}

enum ConformanceExpectations {{
    /// Every key found in each registry's source (not only the survey's), so a vanished registration is caught.
    static let registryKeys: [ConformanceRegistry: [String]] = [
{chr(10).join(key_lines)}
    ]

    static let all: [ConformanceExpectation] = [
{chr(10).join(lines)}
    ]
}}
"""
dest = os.path.join(root, "Tests/MLXLMTests/Conformance/ConformanceExpectations.swift")
open(dest, "w", encoding="utf8").write(out)
reg = sum(1 for mt in by_type if any(mt in keys[k] for k in keys))
print(f"{len(skipped)} CSV rows skipped (no usable model_type):", *skipped, sep="\n  ")
print(f"{len(by_type)} model_types: {reg} registered, {len(by_type) - reg} absent -> {dest}")
for k in keys:
    print(k, len(keys[k]), "registry keys")
